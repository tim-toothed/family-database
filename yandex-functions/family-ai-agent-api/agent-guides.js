function listGuides() {
  return GUIDES.map(({ id, title, summary }) => ({ id, title, summary }));
}

function readGuide(guideId) {
  const guide = GUIDES.find((item) => item.id === String(guideId || '').trim());
  if (!guide) throw new Error(`Guide ${guideId} was not found.`);
  return guide;
}

